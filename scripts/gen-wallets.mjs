#!/usr/bin/env node
// Generates the MeterPass test wallets.
// Private keys go ONLY into .env.wallets (git-ignored). This script prints addresses, never keys.
// Re-running keeps existing keys and only adds missing roles.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { privateKeyToAccount } from "viem/accounts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env.wallets");
const publicPath = join(root, "deployments", "wallets.public.json");

const ROLES = [
  ["DEPLOYER", "deploys contracts, registers the demo merchant identity"],
  ["OWNER", "human owner: root key of the smart account, owns the pass NFTs, revokes and refunds"],
  ["MERCHANT", "API seller: receives tUSD8, submits batch claims"],
  ["AGENT_A", "agent A session key: opens passes inside the policy, signs vouchers"],
  ["AGENT_B", "agent B session key: takes over a pass after reassignment"],
];

const SECP256K1_N = BigInt("0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141");
function newKey() {
  for (;;) {
    const k = randomBytes(32);
    const n = BigInt("0x" + k.toString("hex"));
    if (n > 0n && n < SECP256K1_N) return "0x" + k.toString("hex");
  }
}

const existing = {};
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const m = line.match(/^([A-Z_]+)_PRIVATE_KEY=(0x[0-9a-fA-F]{64})\s*$/);
    if (m) existing[m[1]] = m[2];
  }
}

const lines = [
  "# MeterPass TEST wallets. Generated by scripts/gen-wallets.mjs.",
  "# NEVER commit, paste or share this file. Testnet only.",
];
const pub = {};
let created = 0;
for (const [role, purpose] of ROLES) {
  let key = existing[role];
  if (!key) {
    key = newKey();
    created++;
  }
  const address = privateKeyToAccount(key).address;
  lines.push(`# ${role}: ${purpose}`, `${role}_PRIVATE_KEY=${key}`, `${role}_ADDRESS=${address}`);
  pub[role] = { address, purpose };
}
writeFileSync(envPath, lines.join("\n") + "\n", { mode: 0o600 });
mkdirSync(dirname(publicPath), { recursive: true });
writeFileSync(publicPath, JSON.stringify(pub, null, 2) + "\n");

console.log(`${created} new wallet(s); keys stored in .env.wallets (git-ignored).\n`);
for (const [role] of ROLES) console.log(`${role.padEnd(9)} ${pub[role].address}`);
