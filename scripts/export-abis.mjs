#!/usr/bin/env node
// Copies contract ABIs from the Foundry build into the SDK as typed `as const` exports.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const dest = join(root, "packages", "sdk", "src", "abi");
mkdirSync(dest, { recursive: true });

const contracts = {
  passVaultAbi: ["PassVault.sol", "PassVault"],
  agentIdentityRegistryAbi: ["AgentIdentityRegistry.sol", "AgentIdentityRegistry"],
  reputationRegistryAbi: ["ReputationRegistry.sol", "ReputationRegistry"],
  sessionValidatorAbi: ["MeterPassSessionValidator.sol", "MeterPassSessionValidator"],
  mockTusd8Abi: ["MockTUSD8.sol", "MockTUSD8"],
};

let index = "// Generated by scripts/export-abis.mjs from the Foundry build. Do not edit.\n";
for (const [name, [file, contract]] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(out, file, `${contract}.json`), "utf8"));
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by scripts/export-abis.mjs. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index += `export { ${name} } from "./${name}";\n`;
}
writeFileSync(join(dest, "index.ts"), index);
console.log(`exported ${Object.keys(contracts).length} ABIs to packages/sdk/src/abi`);
